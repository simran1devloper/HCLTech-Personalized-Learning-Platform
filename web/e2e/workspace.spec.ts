import { expect, test, type Page } from '@playwright/test'
import { expectNoA11yViolations, register } from './helpers'

const API = 'http://127.0.0.1:8100'
const SHOTS = '../docs/screenshots'

async function token(page: Page) { return (await page.evaluate(() => localStorage.getItem('learnai_token'))) as string }
async function setGoal(page: Page, role: string) { const r = await page.request.post(`${API}/api/v1/goals`, { data: { role_slug: role, hours_per_week: 5 }, headers: { Authorization: `Bearer ${await token(page)}` } }); expect(r.ok()).toBeTruthy() }

/** Real diagnostic quiz (database or fake-model generated) -> the learning workspace, generated by the real backend with the fake model server. */
async function openWorkspace(page: Page, topic: string) {
  await page.goto('/study')
  await page.getByLabel('Topic').fill(topic); await page.getByRole('button', { name: 'Generate quiz' }).click()
  await expect(page.locator('fieldset').first()).toBeVisible({ timeout: 30_000 })
  const n = await page.locator('fieldset').count()
  for (let i = 0; i < n; i++) { const f = page.locator('fieldset').nth(i); const beta = f.getByRole('radio', { name: 'Beta' }); if (await beta.count()) await beta.check(); else await f.locator('input').first().check() }
  await page.getByRole('button', { name: /Submit quiz/ }).click()
  await page.getByRole('button', { name: 'Generate study material' }).click()
  await expect(page).toHaveURL(/\/study\/learn\/[0-9a-f-]+/)
  await expect(page.getByRole('region', { name: 'Study material pipeline' }).getByText('Complete', { exact: true })).toBeVisible({ timeout: 40_000 })
}

test.describe('AI learning workspace', () => {
  test('personalised header, compact monitor with detail, sticky section nav, rich content and sidebar', async ({ page }) => {
    await register(page); await setGoal(page, 'devops-engineer')
    await openWorkspace(page, 'Docker')
    await expect(page.locator('[data-test=career]')).toHaveText('DevOps Engineer')       // the learner's own goal, not a built-in assumption
    await expect(page.locator('[data-test=topic]')).toHaveText('Docker'); await expect(page.locator('[data-test=level]')).toHaveText(/Beginner|Intermediate|Expert/)
    const mon = page.getByRole('region', { name: 'Study material pipeline' })
    await expect(mon).toContainText('10 of 10 sections ready'); await mon.getByRole('button', { name: 'Expand details' }).click()
    for (const t of ['Overview', 'Key Concepts', 'Deep Dive', 'Flashcards']) await expect(mon.locator('[data-test=pipeline-details]')).toContainText(t)
    await expect(mon.locator('[data-test=pipeline-details]')).toContainText(/Completed · \d/)                                                         // measured time per task
    await expect(page.getByRole('tab')).toHaveCount(10); await expect(page.locator('nav[aria-label="Study sections"]')).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Overview' })).toBeVisible(); await expect(page.getByRole('region', { name: 'Learning objectives' }).or(page.getByLabel('Learning objectives'))).toBeVisible()
    await expect(page.getByLabel('Key takeaways')).toBeVisible(); await expect(page.getByText(/min read/)).toBeVisible()
    const aside = page.getByLabel('Study sidebar'); await expect(aside).toContainText('Table of Contents'); await expect(aside).toContainText('Your Progress'); await expect(aside).toContainText('Recommended Next'); await expect(aside).toContainText('Ask AI Tutor')
    await page.getByRole('tab', { name: 'Key Concepts' }).click(); await expect(page.getByText('Concept 1').first()).toBeVisible(); await expect(page.getByText(/4 key concepts/)).toBeVisible()
    await page.getByRole('tab', { name: 'Deep Dive' }).click(); await expect(page.locator('.shiki').first()).toBeVisible()                                // code is Shiki-highlighted
    await expectNoA11yViolations(page, 'study workspace')
    await page.getByRole('tab', { name: 'Overview' }).click(); await page.screenshot({ path: `${SHOTS}/workspace-desktop.png`, fullPage: true })
  })

  test('bookmarks, understood marks, notes and reading progress persist across a reload and the URL restores the session without regenerating', async ({ page }) => {
    await register(page); await openWorkspace(page, 'Redis')
    const url = page.url()
    await page.getByRole('button', { name: 'Bookmark' }).click(); await page.getByRole('button', { name: 'Mark as Understood' }).click()
    await expect(page.locator('[data-test=completed]')).toHaveText('1 / 10')
    await page.getByLabel('My notes').fill('remember: TTL and eviction'); await expect(page.getByText('Saved', { exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Key Concepts' }).click(); await expect(page.getByText(/2 of 10 sections read/)).toBeVisible()
    let streams = 0; page.on('request', (r) => { if (/generate-content|content-sessions\/.+\/(generate|regenerate|continue)/.test(r.url())) streams++ })
    await page.reload(); await expect(page).toHaveURL(new RegExp(url.split('/study')[1].slice(0, 12)))
    await expect(page.locator('[data-test=topic]')).toHaveText('Redis'); await expect(page.locator('[data-test=completed]')).toHaveText('1 / 10')
    await expect(page.getByRole('region', { name: 'Study material pipeline' })).toContainText('10 of 10 sections ready')
    await page.getByRole('tab', { name: 'Overview' }).click(); await expect(page.getByRole('button', { name: 'Bookmarked' })).toBeVisible(); await expect(page.getByRole('button', { name: 'Understood' })).toBeVisible()
    await expect(page.getByLabel('My notes')).toHaveValue('remember: TTL and eviction'); await expect(page.getByText(/2 of 10 sections read/)).toBeVisible()
    expect(streams).toBe(0)                                                                                                                         // a refresh never regenerates anything
  })

  test('a failed section is shown with its error; targeted retry regenerates only that section', async ({ page }) => {
    await register(page); await page.goto('/study')
    await page.getByLabel('Topic').fill('Lua FLAKY scripting'); await page.getByRole('button', { name: 'Generate quiz' }).click()
    await expect(page.locator('fieldset').first()).toBeVisible({ timeout: 30_000 })
    for (let i = 0; i < 10; i++) await page.locator('fieldset').nth(i).getByRole('radio', { name: 'Beta' }).check()
    await page.getByRole('button', { name: /Submit quiz/ }).click(); await page.getByRole('button', { name: 'Generate study material' }).click()
    const mon = page.getByRole('region', { name: 'Study material pipeline' })
    await expect(mon.getByText('Needs attention', { exact: true })).toBeVisible({ timeout: 40_000 })
    await mon.getByRole('button', { name: 'Expand details' }).click(); await expect(mon.locator('[data-task="flashcards"]')).toHaveAttribute('data-status', 'failed')
    const retries: string[] = []; page.on('request', (r) => { if (r.url().includes('/generate-content/stream')) retries.push(r.postData() ?? '') })
    await mon.getByRole('button', { name: 'Retry Flashcards' }).click()
    await expect(mon.getByText('Complete', { exact: true })).toBeVisible({ timeout: 30_000 })
    expect(retries).toHaveLength(1); expect(JSON.parse(retries[0]).sections).toEqual(['flashcards'])                                                  // not the other nine
  })

  test('knowledge check uses saved questions, grades on the server and never reveals answers beforehand', async ({ page }) => {
    await register(page); await openWorkspace(page, 'Python')
    const html = await page.content(); expect(html).not.toMatch(/correct_options|"correct"/)
    await page.getByRole('button', { name: 'Test your understanding' }).click()
    const check = page.getByLabel('Knowledge check'); await expect(check.locator('fieldset')).toHaveCount(3)
    await expect(check.getByRole('button', { name: 'Check answers' })).toBeDisabled()
    for (let i = 0; i < 3; i++) await check.locator('fieldset').nth(i).locator('input').first().check()
    await check.getByRole('button', { name: 'Check answers' }).click()
    await expect(check.getByText(/\d \/ 3/)).toBeVisible(); await expect(check.getByText(/Correct|Not quite/).first()).toBeVisible(); await expect(check.getByRole('button', { name: 'Try another set' })).toBeVisible()
  })

  test('Ask AI Tutor opens the tutor with this section\'s question prefilled and sends nothing by itself', async ({ page }) => {
    await register(page); await openWorkspace(page, 'Docker')
    await page.getByRole('tab', { name: 'Deep Dive' }).click()
    let chats = 0; page.on('request', (r) => { if (r.url().includes('/tutor/chat')) chats++ })
    await page.getByRole('button', { name: 'Chat with AI Tutor' }).click()
    await expect(page).toHaveURL(/\/tutor\?/); await expect(page.getByLabel('Message the tutor')).toHaveValue(/Deep Dive.*Docker/)
    await page.waitForTimeout(500); expect(chats).toBe(0)
  })

  test('navigation: previous/next buttons and Alt+arrows move between sections and keep the URL in sync', async ({ page }) => {
    await register(page); await openWorkspace(page, 'Docker')
    await page.getByRole('button', { name: /^Key Concepts/ }).last().click(); await expect(page.getByRole('heading', { name: 'Key Concepts' })).toBeVisible(); await expect(page).toHaveURL(/s=key_concepts/)
    await page.keyboard.press('Alt+ArrowRight'); await expect(page.getByRole('heading', { name: 'Deep Dive' })).toBeVisible()
    await page.keyboard.press('Alt+ArrowLeft'); await expect(page.getByRole('heading', { name: 'Key Concepts' })).toBeVisible()
    await page.getByRole('tab', { name: 'Key Concepts' }).focus(); await page.keyboard.press('ArrowRight'); await expect(page.getByRole('heading', { name: 'Deep Dive' })).toBeVisible()
  })

  test('responsive: on a phone nothing overflows horizontally, the section nav scrolls, and the sidebar stacks below the content', async ({ page }) => {
    await page.setViewportSize({ width: 375, height: 800 })
    await register(page); await openWorkspace(page, 'Docker')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const nav = page.getByRole('tablist', { name: 'Study sections' }); expect(await nav.evaluate((e) => e.scrollWidth > e.clientWidth)).toBe(true)         // scrollable, not wrapped off-screen
    const panel = await page.getByRole('tabpanel').boundingBox(); const aside = await page.getByLabel('Study sidebar').boundingBox()
    expect(aside!.y).toBeGreaterThan(panel!.y + panel!.height - 1)                                                                                    // stacked, not beside
    await page.getByRole('region', { name: 'Study material pipeline' }).getByRole('button', { name: 'Expand details' }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `${SHOTS}/workspace-mobile.png`, fullPage: true })
  })
})
